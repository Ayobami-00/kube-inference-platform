def install_foundation(*, dry_run: bool = False) -> dict[str, Any]:
    """Install only AIPerf's namespace and durable result-storage foundation."""
    manifest = load_foundation_manifest()
    _validate_committed_foundation_contract(manifest)
    if dry_run:
        return manifest
    # All Kubernetes name collisions are checked before the first host mutation.
    # This keeps a failed or unmanaged cluster preflight from leaving a newly
    # created node-local directory behind.
    _validate_foundation_cluster(manifest, require_all=False, require_ready=False)
    _prepare_results_directory()
    _run_command(
        [
            _kubectl(),
            "apply",
            "--server-side",
            "--field-manager",
            MANAGED_BY,
            "-f",
            str(kubernetes_assets_root() / "foundation.json"),
        ]
    )
    check_foundation(cluster=True)
    return manifest


def check_foundation(*, cluster: bool = False) -> dict[str, Any]:
    """Validate committed pins and optionally the installed Kubernetes foundation."""
    manifest = load_foundation_manifest()
    _validate_committed_foundation_contract(manifest)
    if cluster:
        if not _results_directory_ready():
            raise BenchError(
                f"benchmark result path is absent or not writable by UID/GID "
                f"{RESULTS_UID}:{RESULTS_GID}: {RESULTS_HOST_PATH}"
            )
        _validate_foundation_cluster(manifest, require_all=True, require_ready=True)
    return {
        "aiperfVersion": AIPERF_VERSION,
        "aiperfImage": AIPERF_IMAGE,
        "namespace": BENCHMARK_NAMESPACE,
        "executor": "kubernetes-job",
        "resultsHostPath": str(RESULTS_HOST_PATH),
        "clusterChecked": cluster,
    }


def run_platform_preflight(cost_profile: str) -> None:
    """Require every previously established hard checkpoint before load generation."""
    root = repository_root()
    environment = os.environ.copy()
    environment["KIP_COST_PROFILE"] = cost_profile
    commands = (
        ["/bin/bash", str(root / "deploy" / "cluster" / "validate.sh")],
        ["/bin/bash", str(root / "deploy" / "gpu" / "validate.sh")],
        ["/bin/bash", str(root / "deploy" / "runtime" / "dispatch.sh"), "check"],
        ["/bin/bash", str(root / "deploy" / "observability" / "validate.sh")],
        [
            "/bin/bash",
            str(root / "deploy" / "observability" / "cost.sh"),
            "check",
        ],
    )
    for command in commands:
        try:
            result = subprocess.run(
                command,
                cwd=root,
                env=environment,
                check=False,
                capture_output=True,
                text=True,
                timeout=300,
            )
        except (FileNotFoundError, subprocess.TimeoutExpired) as error:
            raise ExternalCommandError(f"benchmark preflight could not run {command[1]}") from error
        if result.returncode != 0:
            detail = result.stderr.strip() or result.stdout.strip() or "no diagnostics"
            raise ExternalCommandError(
                f"benchmark preflight failed in {Path(command[1]).name}: {detail}"
            )


def require_no_active_benchmark() -> None:
    """Refuse to overlap AIPerf Jobs on the benchmark namespace."""
    result = _run_command(
        [
            _kubectl(),
            "-n",
            BENCHMARK_NAMESPACE,
            "get",
            "jobs",
            "-l",
            f"app.kubernetes.io/managed-by={MANAGED_BY}",
            "-o",
            "json",
        ]
    )
    try:
        jobs = json.loads(result.stdout).get("items", [])
    except (AttributeError, json.JSONDecodeError) as error:
        raise BenchError("cannot inspect existing benchmark Jobs") from error
    for job in jobs:
        conditions = job.get("status", {}).get("conditions", [])
        terminal = any(
            condition.get("status") == "True" and condition.get("type") in {"Complete", "Failed"}
            for condition in conditions
        )
        if not terminal:
            name = job.get("metadata", {}).get("name", "unknown")
            raise BenchError(f"another benchmark Job is active: {name}")


@dataclass(frozen=True)
class BenchmarkCell:
    """One AIPerf invocation in a larger experiment."""

    concurrency: int
    trial: int
    requests: int
    warmup: bool = False

    @property
    def identifier(self) -> str:
        if self.warmup:
            return "warmup"
        return f"c{self.concurrency}-t{self.trial}"


class BenchmarkExecutor(ABC):
    """Backend boundary for AIPerf execution."""

    @abstractmethod
    def render(self, suite: Suite, profile: CostProfile, run_id: str, cell: BenchmarkCell) -> dict:
        """Render one immutable execution object."""

    @abstractmethod
    def execute(
        self,
        suite: Suite,
        profile: CostProfile,
        run_id: str,
        cell: BenchmarkCell,
        destination: Path,
        timeout_seconds: int,
    ) -> dict[str, Any]:
        """Execute and collect one cell."""


class KubernetesJobExecutor(BenchmarkExecutor):
    """Run AIPerf 0.12 using one ordinary Kubernetes Job per cell/trial."""

