def _utc_now() -> str:
    return datetime.now(UTC).isoformat().replace("+00:00", "Z")


def _kubectl() -> str:
    return os.environ.get("KIP_KUBECTL", "kubectl")


def _run_git_bytes(arguments: list[str], root: Path) -> bytes:
    """Run a read-only Git command used to freeze benchmark provenance."""
    try:
        result = subprocess.run(
            ["git", *arguments],
            cwd=root,
            check=False,
            capture_output=True,
            timeout=30,
        )
    except FileNotFoundError as error:
        raise BenchError("git is required to capture benchmark provenance") from error
    except subprocess.TimeoutExpired as error:
        raise BenchError("timed out while capturing benchmark provenance") from error
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", errors="replace").strip()
        raise BenchError(f"cannot capture benchmark provenance: {detail or 'git failed'}")
    return result.stdout


def capture_repository_identity() -> dict[str, str]:
    """Freeze HEAD and a deterministic digest of the working tree before load."""
    root = repository_root().resolve()
    revision = _run_git_bytes(["rev-parse", "--verify", "HEAD"], root).decode().strip()
    if not re.fullmatch(r"[a-f0-9]{40}", revision):
        raise BenchError("git HEAD is not a full lowercase commit SHA")

    status = _run_git_bytes(["status", "--porcelain=v2", "-z", "--untracked-files=all"], root)
    tracked_diff = _run_git_bytes(["diff", "--binary", "HEAD", "--"], root)
    untracked = _run_git_bytes(["ls-files", "--others", "--exclude-standard", "-z"], root)

    digest = hashlib.sha256()
    digest.update(b"kip-git-workspace-v1\0")
    digest.update(status)
    digest.update(b"\0tracked-diff\0")
    digest.update(tracked_diff)
    for raw_path in sorted(path for path in untracked.split(b"\0") if path):
        relative = Path(os.fsdecode(raw_path))
        candidate = root / relative
        if relative.is_absolute() or ".." in relative.parts:
            raise BenchError("git returned an unsafe untracked path")
        digest.update(b"\0untracked\0")
        digest.update(raw_path)
        digest.update(b"\0")
        try:
            if candidate.is_symlink():
                digest.update(b"symlink\0")
                digest.update(os.fsencode(os.readlink(candidate)))
            elif candidate.is_file():
                digest.update(b"file\0")
                digest.update(candidate.read_bytes())
            else:
                raise BenchError(f"untracked benchmark input is not a file: {relative}")
        except OSError as error:
            raise BenchError(
                f"cannot hash untracked benchmark input {relative}: {error}"
            ) from error

    return {
        "revision": revision,
        "treeState": "dirty" if status else "clean",
        "workspaceSha256": digest.hexdigest(),
    }


def _require_loaded_inputs_current(suite: Suite, profile: CostProfile) -> None:
    """Reject objects loaded before their committed source changed on disk."""
    current_suite = load_suite(suite.name, root=suite.path.parent)
    current_profile = load_cost_profile(profile.name, root=profile.path.parent)
    if current_suite.sha256 != suite.sha256:
        raise BenchError("benchmark suite changed after it was loaded")
    if current_profile.sha256 != profile.sha256:
        raise BenchError("cost profile changed after it was loaded")


def _run_command(
    arguments: list[str],
    *,
    input_text: str | None = None,
    timeout: float | None = None,
    check: bool = True,
) -> subprocess.CompletedProcess[str]:
    try:
        result = subprocess.run(
            arguments,
            input=input_text,
            text=True,
            capture_output=True,
            check=False,
            timeout=timeout,
        )
    except FileNotFoundError as error:
        raise ExternalCommandError(f"required command not found: {arguments[0]}") from error
    except subprocess.TimeoutExpired as error:
        raise ExternalCommandError(f"command timed out: {' '.join(arguments[:3])}") from error
    if check and result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "no diagnostic output"
        raise ExternalCommandError(f"command failed ({result.returncode}): {detail}")
    return result


def load_foundation_manifest() -> dict[str, Any]:
    """Load the committed namespace/storage foundation."""
    path = kubernetes_assets_root() / "foundation.json"
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise BenchError(f"cannot load AIPerf foundation manifest: {error}") from error
    if not isinstance(value, dict) or value.get("kind") != "List":
        raise BenchError("AIPerf foundation manifest must be a Kubernetes List")
    return value


def _foundation_resources(
    manifest: dict[str, Any],
) -> dict[tuple[str, str, str | None], dict[str, Any]]:
    """Index and validate the five committed foundation resources."""
    items = manifest.get("items")
    if not isinstance(items, list):
        raise BenchError("AIPerf foundation manifest items must be a list")
    resources: dict[tuple[str, str, str | None], dict[str, Any]] = {}
    for item in items:
        if not isinstance(item, dict):
            raise BenchError("AIPerf foundation resources must be JSON objects")
        metadata = item.get("metadata")
        if not isinstance(metadata, dict):
            raise BenchError("AIPerf foundation resource metadata must be an object")
        kind = item.get("kind")
        name = metadata.get("name")
        namespace = metadata.get("namespace")
        if not isinstance(kind, str) or not isinstance(name, str):
            raise BenchError("AIPerf foundation resources require kind and metadata.name")
        if namespace is not None and not isinstance(namespace, str):
            raise BenchError("AIPerf foundation resource namespaces must be strings")
        identity = (kind, name, namespace)
        if identity in resources:
            raise BenchError(f"duplicate AIPerf foundation resource: {kind}/{name}")
        resources[identity] = item
    if set(resources) != set(_FOUNDATION_IDENTITIES):
        raise BenchError("AIPerf foundation manifest contains an unexpected resource set")
    return resources


def _metadata_projection(expected: dict[str, Any], live: dict[str, Any]) -> dict[str, Any]:
    """Project only KIP-owned labels plus all Pod Security Admission controls."""
    expected_metadata = expected.get("metadata", {})
    live_metadata = live.get("metadata", {})
    expected_labels = expected_metadata.get("labels", {})
    live_labels = live_metadata.get("labels", {})
    if not isinstance(expected_labels, dict) or not isinstance(live_labels, dict):
        return {"invalidLabels": True}
    label_keys = set(expected_labels)
    label_keys.update(
        key
        for key in live_labels
        if isinstance(key, str) and key.startswith("pod-security.kubernetes.io/")
    )
    return {
        "name": live_metadata.get("name"),
        "namespace": live_metadata.get("namespace"),
        "labels": {key: live_labels.get(key) for key in sorted(label_keys)},
    }


def _foundation_projection(expected: dict[str, Any], value: dict[str, Any]) -> dict[str, Any]:
    """Return a stable security/storage projection without API-managed fields."""
    kind = expected["kind"]
    projection: dict[str, Any] = {
        "apiVersion": value.get("apiVersion"),
        "kind": value.get("kind"),
        "metadata": _metadata_projection(expected, value),
    }
    spec = value.get("spec", {})
    if not isinstance(spec, dict):
        spec = {"invalidSpec": True}
    if kind == "ServiceAccount":
        projection["automountServiceAccountToken"] = value.get("automountServiceAccountToken")
    elif kind == "ConfigMap":
        projection["data"] = value.get("data")
    elif kind == "PersistentVolume":
        capacity = spec.get("capacity", {})
        projection["spec"] = {
            "capacity": {
                "storage": capacity.get("storage") if isinstance(capacity, dict) else None
            },
            "accessModes": sorted(spec.get("accessModes", []))
            if isinstance(spec.get("accessModes"), list)
            else spec.get("accessModes"),
            "persistentVolumeReclaimPolicy": spec.get("persistentVolumeReclaimPolicy"),
            "storageClassName": spec.get("storageClassName", ""),
            "volumeMode": spec.get("volumeMode", "Filesystem"),
            "hostPath": spec.get("hostPath"),
            "nodeAffinity": spec.get("nodeAffinity"),
        }
    elif kind == "PersistentVolumeClaim":
        resources = spec.get("resources", {})
        requests = resources.get("requests", {}) if isinstance(resources, dict) else {}
        projection["spec"] = {
            "accessModes": sorted(spec.get("accessModes", []))
            if isinstance(spec.get("accessModes"), list)
            else spec.get("accessModes"),
            "storageClassName": spec.get("storageClassName", ""),
            "volumeName": spec.get("volumeName"),
            "volumeMode": spec.get("volumeMode", "Filesystem"),
            "resources": {
                "requests": {
                    "storage": requests.get("storage") if isinstance(requests, dict) else None
                }
            },
        }
    return projection


def _first_projection_difference(
    expected: Any, actual: Any, path: str = "resource"
) -> tuple[str, Any, Any] | None:
    """Locate one deterministic difference for an actionable drift diagnostic."""
    if isinstance(expected, dict) and isinstance(actual, dict):
        keys = sorted(set(expected) | set(actual))
        for key in keys:
            if key not in expected:
                return f"{path}.{key}", None, actual[key]
            if key not in actual:
                return f"{path}.{key}", expected[key], None
            difference = _first_projection_difference(expected[key], actual[key], f"{path}.{key}")
            if difference is not None:
                return difference
        return None
    if expected != actual:
        return path, expected, actual
    return None


def _get_foundation_resource(
    kind: str, name: str, *, namespace: str | None = None
) -> dict[str, Any] | None:
    arguments = [_kubectl()]
    if namespace:
        arguments.extend(["-n", namespace])
    arguments.extend(
        ["get", _KUBECTL_FOUNDATION_KINDS[kind], name, "--ignore-not-found", "-o", "json"]
    )
    result = _run_command(arguments, check=False)
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip() or "no diagnostic output"
        raise ExternalCommandError(f"cannot inspect existing {kind}/{name}: {detail}")
    if not result.stdout.strip():
        return None
    try:
        resource = json.loads(result.stdout)
    except json.JSONDecodeError as error:
        raise BenchError(f"cannot parse existing {kind}/{name}") from error
    if not isinstance(resource, dict):
        raise BenchError(f"existing {kind}/{name} is not a Kubernetes object")
    return resource


def _validate_live_foundation_resource(
    expected: dict[str, Any], live: dict[str, Any], *, require_ready: bool
) -> None:
    kind = expected["kind"]
    name = expected["metadata"]["name"]
    labels = live.get("metadata", {}).get("labels", {})
    if not isinstance(labels, dict) or labels.get("app.kubernetes.io/managed-by") != MANAGED_BY:
        raise BenchError(f"refusing unmanaged {kind}/{name}; expected managed-by={MANAGED_BY}")
    expected_projection = _foundation_projection(expected, expected)
    live_projection = _foundation_projection(expected, live)
    difference = _first_projection_difference(expected_projection, live_projection)
    if difference is not None:
        path, expected_value, live_value = difference
        raise BenchError(
            f"benchmark foundation drift for {kind}/{name} at {path}: "
            f"expected {expected_value!r}, found {live_value!r}"
        )
    if kind == "PersistentVolumeClaim":
        status = live.get("status", {})
        phase = status.get("phase") if isinstance(status, dict) else None
        expected_capacity = expected["spec"]["resources"]["requests"]["storage"]
        live_capacity = (
            status.get("capacity", {}).get("storage")
            if isinstance(status, dict) and isinstance(status.get("capacity"), dict)
            else None
        )
        if phase == "Bound" and live_capacity != expected_capacity:
            raise BenchError(
                f"benchmark foundation drift for {kind}/{name} at status.capacity.storage: "
                f"expected {expected_capacity!r}, found {live_capacity!r}"
            )
        if require_ready and phase != "Bound":
            raise BenchError(f"benchmark results PVC is not Bound (phase={phase or 'unknown'})")


def _validate_foundation_cluster(
    manifest: dict[str, Any], *, require_all: bool, require_ready: bool
) -> None:
    resources = _foundation_resources(manifest)
    benchmark_namespace_present: bool | None = None
    for identity in _FOUNDATION_IDENTITIES:
        expected = resources[identity]
        kind, name, namespace = identity
        # A namespaced object cannot exist while its namespace is absent, and
        # kubectl reports that condition as an error even with
        # --ignore-not-found. Keep inspecting cluster-scoped resources so a
        # conflicting PV is still rejected before host storage is created.
        if namespace == BENCHMARK_NAMESPACE and benchmark_namespace_present is False:
            if require_all:
                raise BenchError(f"required benchmark resource is missing: {kind}/{name}")
            continue
        live = _get_foundation_resource(kind, name, namespace=namespace)
        if kind == "Namespace" and name == BENCHMARK_NAMESPACE:
            benchmark_namespace_present = live is not None
        if live is None:
            if require_all:
                raise BenchError(f"required benchmark resource is missing: {kind}/{name}")
            continue
        _validate_live_foundation_resource(expected, live, require_ready=require_ready)


def _prepare_results_directory() -> None:
    """Create the fixed node-local result path for the non-root AIPerf Pod."""
    marker = RESULTS_HOST_PATH / RESULTS_OWNERSHIP_MARKER
    if os.path.lexists(RESULTS_HOST_PATH):
        if not _results_directory_owned():
            raise BenchError(
                f"refusing existing unowned benchmark result path: {RESULTS_HOST_PATH}"
            )
        if not _results_directory_ready():
            raise BenchError(
                f"benchmark result path ownership or permissions drifted: {RESULTS_HOST_PATH}"
            )
        return
    if not RESULTS_HOST_PATH.parent.is_dir() or RESULTS_HOST_PATH.parent.is_symlink():
        raise BenchError(
            f"benchmark result parent must be an existing real directory: "
            f"{RESULTS_HOST_PATH.parent}"
        )

    prefix: list[str] = []
    if os.geteuid() != 0:
        try:
            validated = subprocess.run(
                ["sudo", "-n", "true"],
                check=False,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=10,
            )
        except FileNotFoundError as error:
            raise ExternalCommandError(
                "root access or passwordless sudo is required for benchmark storage"
            ) from error
        except subprocess.TimeoutExpired as error:
            raise ExternalCommandError(
                "timed out validating passwordless sudo for benchmark storage"
            ) from error
        if validated.returncode != 0:
            raise ExternalCommandError(
                "root access or passwordless sudo is required for benchmark storage"
            )
        prefix = ["sudo"]

    created = False
    try:
        _run_command([*prefix, "mkdir", str(RESULTS_HOST_PATH)], timeout=30)
        created = True
        _run_command(
            [
                *prefix,
                "chown",
                f"{RESULTS_UID}:{RESULTS_GID}",
                str(RESULTS_HOST_PATH),
            ],
            timeout=30,
        )
        _run_command([*prefix, "chmod", "0770", str(RESULTS_HOST_PATH)], timeout=30)
        with tempfile.NamedTemporaryFile("w", encoding="utf-8") as source:
            source.write(RESULTS_OWNERSHIP_CONTENT)
            source.flush()
            _run_command(
                [
                    *prefix,
                    "install",
                    "-m",
                    "0444",
                    "-o",
                    str(RESULTS_UID),
                    "-g",
                    str(RESULTS_GID),
                    source.name,
                    str(marker),
                ],
                timeout=30,
            )
    except Exception:
        if created:
            _run_command([*prefix, "rmdir", str(RESULTS_HOST_PATH)], check=False, timeout=30)
        raise


def _results_directory_owned() -> bool:
    """Require the explicit marker written only when KIP creates the directory."""
    marker = RESULTS_HOST_PATH / RESULTS_OWNERSHIP_MARKER
    try:
        directory_metadata = RESULTS_HOST_PATH.lstat()
        marker_metadata = marker.lstat()
        marker_content = marker.read_text(encoding="utf-8")
    except OSError:
        return False
    return (
        stat.S_ISDIR(directory_metadata.st_mode)
        and not stat.S_ISLNK(directory_metadata.st_mode)
        and stat.S_ISREG(marker_metadata.st_mode)
        and not stat.S_ISLNK(marker_metadata.st_mode)
        and marker_content == RESULTS_OWNERSHIP_CONTENT
    )


def _results_directory_ready() -> bool:
    try:
        metadata = RESULTS_HOST_PATH.stat()
    except OSError:
        return False
    mode = stat.S_IMODE(metadata.st_mode)
    return (
        _results_directory_owned()
        and RESULTS_HOST_PATH.is_dir()
        and metadata.st_uid == RESULTS_UID
        and metadata.st_gid == RESULTS_GID
        and mode & stat.S_IWUSR != 0
        and mode & stat.S_IWGRP != 0
    )


def _extract_artifact_archive(archive: Path, destination: Path) -> None:
    """Extract one AIPerf archive without accepting links or path traversal."""
    destination_parent = destination.parent.resolve()
    try:
        with tarfile.open(archive, "r:gz") as source:
            members = source.getmembers()
            if not members:
                raise ExternalCommandError(f"AIPerf artifact archive is empty: {archive}")
            archive_root = members[0]
            if archive_root.name.rstrip("/") != destination.name or not archive_root.isdir():
                raise ExternalCommandError(
                    "AIPerf artifact archive does not contain the expected root directory"
                )
            for member in members:
                parts = Path(member.name).parts
                if (
                    not parts
                    or parts[0] != destination.name
                    or Path(member.name).is_absolute()
                    or ".." in parts
                    or "\\" in member.name
                    or not (member.isdir() or member.isfile())
                ):
                    raise ExternalCommandError(
                        f"AIPerf artifact archive contains an unsafe member: {member.name}"
                    )
                target = destination.parent.joinpath(*parts).resolve()
                try:
                    target.relative_to(destination_parent)
                except ValueError as error:
                    raise ExternalCommandError(
                        f"AIPerf artifact archive escapes its destination: {member.name}"
                    ) from error
            if destination.exists():
                raise ExternalCommandError(
                    f"AIPerf artifact destination already exists: {destination}"
                )
            for member in members:
                target = destination.parent.joinpath(*Path(member.name).parts)
                if member.isdir():
                    target.mkdir(parents=True, exist_ok=True)
                    continue
                target.parent.mkdir(parents=True, exist_ok=True)
                payload = source.extractfile(member)
                if payload is None:
                    raise ExternalCommandError(f"cannot read AIPerf artifact member: {member.name}")
                with payload, target.open("xb") as output:
                    shutil.copyfileobj(payload, output)
            if not destination.is_dir():
                raise ExternalCommandError(
                    "AIPerf artifact archive did not produce the expected directory"
                )
    except (OSError, tarfile.TarError) as error:
        raise ExternalCommandError(f"cannot extract AIPerf artifact archive: {error}") from error


def _owned_resource(kind: str, name: str, *, namespace: str | None = None) -> bool:
    canonical_kind = {
        "namespace": "Namespace",
        "serviceaccount": "ServiceAccount",
        "configmap": "ConfigMap",
        "persistentvolume": "PersistentVolume",
        "persistentvolumeclaim": "PersistentVolumeClaim",
    }.get(kind, kind)
    resource = _get_foundation_resource(canonical_kind, name, namespace=namespace)
    if resource is None:
        return False
    try:
        owner = resource["metadata"]["labels"]["app.kubernetes.io/managed-by"]
    except (KeyError, TypeError) as error:
        raise BenchError(f"cannot verify ownership of existing {kind}/{name}") from error
    if owner != MANAGED_BY:
        raise BenchError(f"refusing unmanaged {kind}/{name}; expected managed-by={MANAGED_BY}")
    return True


